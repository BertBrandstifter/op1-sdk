#!/usr/bin/env python3
"""Generate mo_tables.h: MONO's tables: ladder coefficients per semitone, the contour curve (x^3.3), contour and
glide times, osc 2 / 3 frequency steps, mixer levels, tanh (the self-oscillation limit), exp2 / log2.
Run: python3 gen_tables.py"""
import math

SR, BLK, SUB = 88200, 128, 32


def arr(name, ctype, vals, comment, per=10):
    out = [f"/* {comment} */", f"static const {ctype} {name}[{len(vals)}] = {{"]
    out += ["    " + ", ".join(str(v) for v in vals[i:i + per]) + "," for i in range(0, len(vals), per)]
    return out + ["};", ""]


# ladder: four one-pole stages y += g (x - y), feedback from stage 4 two samples back (one sample
# of 44.1 kHz: the resonance sits below the poles, the passband brighter than an
# analogue ladder tuned to the same pitch). Per semitone s = 0 .. 132 above 20 Hz: g such that the
# loop's resonance (phase -180 deg) is at 20 Hz * 2^(s/12), and the loop gain there (k at the
# threshold of self-oscillation / 4, Q12). Up to 20 kHz; above it g stays (the filter is open).
DELAY = 2


def loop_at(g, w):
    z = complex(math.cos(w), math.sin(w))
    st = g / (1 - (1 - g) / z)
    return st ** 4 * z ** -DELAY


def resonance(g):
    """lowest w where the loop phase is -180 deg (imag turns positive with real < 0), 1 / |loop| there"""
    n = 4000
    prev = 1e-6
    for i in range(1, n + 1):
        w = math.pi * 0.999 * i / n
        G = loop_at(g, w)
        if G.imag >= 0 and G.real < 0:
            lo, hi = prev, w
            break
        prev = w
    for _ in range(50):
        m = (lo + hi) / 2
        G = loop_at(g, m)
        if G.imag >= 0 and G.real < 0:
            hi = m
        else:
            lo = m
    w = (lo + hi) / 2
    return w, 1 / abs(loop_at(g, w))


lad, acr = [], []
for st in range(133):
    f = min(20 * 2 ** (st / 12), 20000)
    lo, hi = 1e-7, 0.999
    for _ in range(60):
        m = (lo + hi) / 2
        if resonance(m)[0] * SR / (2 * math.pi) < f:
            lo = m
        else:
            hi = m
    g = (lo + hi) / 2
    lad.append(min(32767, round(g * 32768)))
    acr.append(round(resonance(g)[1] / 4 * 4096))
tnh = [round(math.tanh(-4 + i / 64) * 16384) for i in range(513)]               # Q14, x = -4 .. 4
ex2 = [round(2 ** (i / 256) * 65536) for i in range(257)]
lg2 = [round(math.log2(1 + i / 256) * 65536) for i in range(257)]

# contour curve: x^3.3 (attack 1 - (1 - t/T)^3.3, decay (1 - t/T)^3.3), x = i / 64, Q15
pw = [round((i / 64) ** 3.3 * 32767) for i in range(65)]
# contour times, 32 steps: 1 ms .. 10 s (log); the ramp's step per 32 samples, Q24 (1.0 = 2^24)
TIMES = [0.001 * 10 ** (4 * n / 31) for n in range(32)]
rate = [min(1 << 24, round((1 << 24) * SUB / (t * SR))) for t in TIMES]
tms = [round(t * 10000) for t in TIMES]                                         # 0.1 ms (screen)
short = round((1 << 24) * SUB / (0.021 * SR))                                   # release off: 21 ms
# glide: off, then 15 steps 10 ms .. 2 s (log), constant time whatever the interval: per block, Q16
GLIDES = [0] + [0.010 * 200 ** ((k - 1) / 14) for k in range(1, 16)]
gli = [0] + [min(65535, round(65536 * BLK / (t * SR))) for t in GLIDES[1:]]
gms = [round(t * 1000) for t in GLIDES]
# osc 2 / 3 frequency: 31 steps, 15 = unison; cents
POS = [3, 6, 10, 15, 20, 30, 40, 50, 75, 100, 200, 300, 400, 500, 700]
CENTS = [-c for c in reversed(POS)] + [0] + POS
freq = [round(2 ** (c / 1200) * 65536) for c in CENTS]
# mixer levels 0..15 = (n / 15)^1.5 (fine at the bottom: a touch of noise), Q15
lvl = [round((n / 15) ** 1.5 * 32767) for n in range(16)]

out = ["/* generated by gen_tables.py - do not edit */", "#ifndef MO_TABLES_H", "#define MO_TABLES_H", "",
       "#include <stdint.h>", ""]
out += arr("mo_ladder", "uint16_t", lad, "ladder stage g, Q15: the loop resonates at 20 Hz * 2^(s/12) (up to 20 kHz), s = 0..132")
out += arr("mo_acr", "uint16_t", acr, "loop gain k at the threshold of self-oscillation / 4, Q12, per semitone as mo_ladder")
out += arr("mo_tanh", "int16_t", tnh, "tanh(x), Q14, x = -4 .. 4 in 512 steps of 1/64 (+ guard)", 12)
out += arr("mo_texp2", "uint32_t", ex2, "2^(i/256), Q16, i = 0..256", 8)
out += arr("mo_tlog2", "uint32_t", lg2, "log2(1 + i/256), Q16, i = 0..256", 8)
out += arr("mo_pow", "uint16_t", pw, "contour curve x^3.3, Q15, x = i/64")
out += arr("mo_rate", "uint32_t", rate, "contour ramp step per 32 samples, Q24: 1 ms .. 10 s in 32 log steps", 8)
out += arr("mo_time", "uint32_t", tms, "contour times, 0.1 ms", 8)
out += [f"#define MO_SHORT_RATE {short}u /* release off: 21 ms */", ""]
out += arr("mo_glide", "uint16_t", gli, "glide: fraction of the start offset per block, Q16 (0 = off): 10 ms .. 2 s")
out += arr("mo_tglide_ms", "uint16_t", gms, "glide times, ms")
out += arr("mo_freq", "uint32_t", freq, "osc 2 / 3 frequency ratio, Q16, 31 steps (15 = unison)", 7)
out += arr("mo_tcents", "int16_t", CENTS, "osc 2 / 3 frequency steps, cents", 16)
out += arr("mo_level", "uint16_t", lvl, "mixer level (n / 15)^1.5, Q15", 8)
out += ["#endif", ""]
open("mo_tables.h", "w").write("\n".join(out))
print("rate", rate[0], rate[-1], "glide", gli[1], gli[-1], "freq", len(freq))
