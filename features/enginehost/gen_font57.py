def rows(ch):
    r = G[ch].split()
    assert len(r) == 7 and all(len(x) == 5 for x in r), ch
    return [int(x.replace('#', '1').replace('.', '0'), 2) for x in r]


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    chars = [chr(c) for c in range(0x20, 0x7f)]
    assert set(chars) == set(G), sorted(set(chars) ^ set(G))
    out = ["/* 5 x 7 dot-matrix font, ASCII 0x20 .. 0x7e: 7 rows per glyph, bit 4 = left column.",
           " * Generated by gen_font57.py (the glyphs are drawn there); do not edit. */",
           "static const uint8_t eh_font57[95][7] = {"]
    for ch in chars:
        shown = {'\\': 'backslash', "'": "quote"}.get(ch, ch)
        out.append("    { " + ", ".join(f"0x{v:02x}" for v in rows(ch)) + " },   /* " + shown + " */")
    out.append("};")
    with open(os.path.join(here, "eh_font57.h"), "w") as f:
        f.write("\n".join(out) + "\n")
    if "--png" in sys.argv:
        from PIL import Image
        img = Image.new("RGB", (16 * 8 * 4, 6 * 10 * 4), (0, 0, 0))
        for i, ch in enumerate(chars):
            for y, v in enumerate(rows(ch)):
                for x in range(5):
                    if v >> (4 - x) & 1:
                        for dy in range(3):
                            for dx in range(3):
                                img.putpixel(((i % 16 * 8 + x) * 4 + dx, (i // 16 * 10 + y) * 4 + dy), (200, 232, 60))
        img.save(sys.argv[sys.argv.index("--png") + 1])


if __name__ == "__main__":
    main()
