#!/usr/bin/env python3
"""Generate wp_tables.h: WARP's single-cycle waves (257 points, the last = the first, for linear
interpolation) and the DECAY knob's per-block decay factors. Run: python3 gen_tables.py"""
import math

N, LEVEL = 256, 24576
SR, BLOCK = 88200, 128


def norm(v):
    m = max(abs(x) for x in v) or 1
    return [round(x / m * LEVEL) for x in v]


def additive(h):
    return [sum(a * math.sin(2 * math.pi * k * i / N) for k, a in h) for i in range(N)]


waves = {
    "SINE": [math.sin(2 * math.pi * i / N) for i in range(N)],
    "TRI": [1 - 4 * abs(i / N - 0.5) for i in range((N))],
    "SAW": [2 * i / N - 1 for i in range(N)],
    "SQUARE": [1 if i < N / 2 else -1 for i in range(N)],
    "PULSE": [1 if i < N / 4 else -1 for i in range(N)],
    "HALF": [max(0.0, math.sin(2 * math.pi * i / N)) * 2 - 0.6366 for i in range(N)],
    "ORGAN": additive([(1, 1), (2, 0.5), (3, 0.4), (4, 0.25), (6, 0.15), (8, 0.1)]),
    "VOX": additive([(1, 0.6), (2, 0.9), (3, 1.0), (4, 0.5), (7, 0.35), (8, 0.3), (9, 0.2)]),
}
out = ["/* generated by gen_tables.py - do not edit */", "#ifndef WP_TABLES_H", "#define WP_TABLES_H", "",
       "#include <stdint.h>", "", f"#define WP_WAVES {len(waves)}", "",
       "static const int16_t wp_wave[WP_WAVES][257] = {"]
for name, v in waves.items():
    v = norm(v)
    v.append(v[0])
    out.append(f"    {{   /* {name} */")
    for i in range(0, 257, 12):
        out.append("        " + ", ".join(str(x) for x in v[i:i + 12]) + ",")
    out.append("    },")
out.append("};")
# DECAY knob (32 steps + guard): tau 10 ms .. 4 s, exponential; per-block factor Q15
taus = [0.01 * (400 ** (k / 31)) for k in range(32)]
f = [round(math.exp(-BLOCK / SR / t) * 32768) for t in taus]
f = [min(x, 32767) for x in f] + [min(f[-1], 32767)]
out += ["", "/* per-block (128 samples) envelope decay, Q15, DECAY knob in 32 steps: tau 10 ms .. 4 s */",
        "static const uint16_t wp_decay[33] = {", "    " + ", ".join(str(x) for x in f[:11]) + ",",
        "    " + ", ".join(str(x) for x in f[11:22]) + ",", "    " + ", ".join(str(x) for x in f[22:]) + ",", "};",
        "", "#endif", ""]
open("wp_tables.h", "w").write("\n".join(out))
print("waves:", ", ".join(waves))
