#!/usr/bin/env python3
"""Generate tr_tables.h: TRIO's filter coefficient table (CUTOFF knob -> trapezoidal SVF g, Q15, 30 Hz
.. 16 kHz exponential, 65 points), interval ratios (-24..+24 semitones, Q16) and the FDECAY knob's
per-block decay factors. Run: python3 gen_tables.py"""
import math

SR, BLOCK = 88200, 128
f = []
for k in range(65):
    fc = 30 * ((16000 / 30) ** (k / 64))        # 30 Hz .. 16 kHz
    f.append(round(math.tan(math.pi * fc / SR) * 32768))            # trapezoidal SVF g
ratio = [round(2 ** (s / 12) * 65536) for s in range(-24, 25)]
taus = [0.005 * (400 ** (k / 31)) for k in range(32)]    # 5 ms .. 2 s
dec = [min(32767, round(math.exp(-BLOCK / SR / t) * 32768)) for t in taus] + [None]
dec[-1] = dec[-2]
out = ["/* generated by gen_tables.py - do not edit */", "#ifndef TR_TABLES_H", "#define TR_TABLES_H", "",
       "#include <stdint.h>", "",
       "/* trapezoidal (Simper) SVF g = tan(pi fc / 88200), Q15, CUTOFF in 64 steps (+ guard): 30 Hz .. 16 kHz */",
       "static const uint16_t tr_cut[65] = {"]
for i in range(0, 65, 11):
    out.append("    " + ", ".join(str(x) for x in f[i:i + 11]) + ",")
out += ["};", "", "/* 2^(s / 12), Q16, s = -24 .. +24 */", "static const uint32_t tr_ratio[49] = {"]
for i in range(0, 49, 8):
    out.append("    " + ", ".join(str(x) for x in ratio[i:i + 8]) + ",")
out += ["};", "", "/* per-block (128 samples) filter envelope decay, Q15, FDECAY in 32 steps: 5 ms .. 2 s */",
        "static const uint16_t tr_decay[33] = {"]
for i in range(0, 33, 11):
    out.append("    " + ", ".join(str(x) for x in dec[i:i + 11]) + ",")
out += ["};", "", "#endif", ""]
open("tr_tables.h", "w").write("\n".join(out))
print("cut", f[0], f[32], f[64])
