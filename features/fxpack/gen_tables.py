#!/usr/bin/env python3
"""Generate fp_tables.h (FXPACK lookup tables). Run: python3 gen_tables.py > fp_tables.h"""
import math

FS = 44100.0
out = ["/* generated by gen_tables.py - do not edit */", "#ifndef FP_TABLES_H", "#define FP_TABLES_H", "",
       "#include <stdint.h>", ""]


def table(name, ctype, vals, per=12, comment=""):
    if comment:
        out.append(f"/* {comment} */")
    out.append(f"static const {ctype} {name}[{len(vals)}] = {{")
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    out.append("")


def clamp16(v):
    return max(-32768, min(32767, int(round(v))))


table("fp_sin", "int16_t", [clamp16(32767 * math.sin(2 * math.pi * i / 256)) for i in range(257)],
      comment="sin(2 pi i / 256), Q15, 257 entries (last = first) for interpolation")
table("fp_exp2", "uint16_t", [int(round(32768 * 2 ** (i / 16))) if i < 16 else 65535 for i in range(17)],
      comment="2^(i/16), Q15 (i = 16 saturates to 65535)")


def logf(i, lo, hi, n=256):
    return lo * (hi / lo) ** (i / (n - 1))


table("fp_ap", "int16_t",
      [clamp16(32767 * (math.tan(math.pi * logf(i, 80, 10000) / FS) - 1) / (math.tan(math.pi * logf(i, 80, 10000) / FS) + 1))
       for i in range(256)],
      comment="first-order allpass coefficient (t-1)/(t+1), t = tan(pi fc / fs), fc 80 Hz .. 10 kHz log, Q15")
table("fp_svf_g", "int32_t", [int(round(65536 * math.tan(math.pi * logf(i, 20, 19000) / FS))) for i in range(256)],
      comment="SVF g = tan(pi fc / fs), fc 20 Hz .. 19 kHz log, Q16")


def curve(f):
    vals = []
    for i in range(257):
        x = (i - 128) / 128.0
        vals.append(clamp16(32767 * f(x)))
    return vals


curves = [
    ("SOFT", lambda x: math.tanh(2.5 * x) / math.tanh(2.5)),
    ("HARD", lambda x: max(-1, min(1, 1.6 * x))),
    ("DIODE", lambda x: (1 - math.exp(-4 * x)) / (1 - math.exp(-4)) if x >= 0 else -0.55 * (1 - math.exp(5 * x)) / (1 - math.exp(-5))),
    ("FUZZ", lambda x: math.copysign(1 - math.exp(-9 * abs(x)), x) * (1.0 if x >= 0 else 0.8)),
    ("CHEBY", lambda x: 0.5 * x + 0.5 * (4 * x ** 3 - 3 * x)),
]
vals = []
for _, f in curves:
    vals += curve(f)
table("fp_curve", "int16_t", vals, comment="waveshaper curves " + " ".join(n for n, _ in curves) +
      ", 257 points each over -1..1, Q15")
out.append(f"#define FP_CURVES {len(curves)}")
out.append("")
out.append("#endif")
print("\n".join(out))
